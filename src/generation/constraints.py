"""Constrained-Hamiltonian primitives: canonical Poisson brackets and the
first-class / second-class classification of a set of constraints.

This is *detection and classification only* -- it stops short of Dirac-bracket
construction and of the full Dirac-Bergmann consistency iteration (secondary
constraints are flagged, not computed). See `ostrogradski_hamiltonian.analyzeDegenerateLagrangian`
for the caller that produces the constraints from a degenerate Lagrangian.
"""

from dataclasses import dataclass, field

import sympy as sp


@dataclass
class PrimaryConstraint:
    """A relation phi(Q, P) = 0 that must hold on the primary constraint surface."""

    expression: sp.Expr
    origin: str  # human-readable note on where it came from


@dataclass
class DegenerateLagrangianResult:
    """What `ostrogradskiHamiltonian` returns instead of a Hamiltonian dict when
    the Lagrangian is degenerate (the top-momentum relation cannot be inverted).

    A result object, deliberately not an exception: the constraint structure is
    the useful output.
    """

    order: int
    positionSymbols: list          # flat list of canonical position symbols Q...
    momentumSymbols: list          # flat list of canonical momentum symbols P...
    canonicalHamiltonian: sp.Expr  # H_c on the primary surface (best effort)
    primaryConstraints: list       # list[PrimaryConstraint]
    poissonBracketMatrix: sp.Matrix  # C_ab = {phi_a, phi_b}
    constraintClass: list          # "first-class" | "second-class" | "first-class (pending secondary)"
    firstClassCount: int
    secondClassCount: int
    secondaryConstraintsExpected: bool
    detail: str
    degenerate: bool = True
    multiplierSymbols: list = field(default_factory=list)  # undetermined velocities u_i

    def summary(self):
        lines = [
            f"Degenerate Lagrangian (order {self.order}). "
            f"{len(self.primaryConstraints)} primary constraint(s): "
            f"{self.firstClassCount} first-class, {self.secondClassCount} second-class."
        ]
        for constraint, klass in zip(self.primaryConstraints, self.constraintClass):
            lines.append(f"  {klass:>28}:  {constraint.expression} = 0   ({constraint.origin})")
        lines.append(f"  Poisson-bracket matrix C_ab = {{phi_a, phi_b}}:")
        lines.append(f"    {self.poissonBracketMatrix.tolist()}")
        lines.append(f"  canonical H (primary surface) = {self.canonicalHamiltonian}")
        if self.secondaryConstraintsExpected:
            lines.append(
                "  consistency {phi, H} does not vanish weakly for at least one constraint "
                "-> a secondary constraint is required (Dirac-Bergmann iteration not performed)."
            )
        lines.append(f"  {self.detail}")
        return "\n".join(lines)


def poissonBracket(f, g, positions, momenta):
    """Canonical Poisson bracket {f, g} = sum_i (df/dQ_i dg/dP_i - df/dP_i dg/dQ_i).

    `positions` and `momenta` are equal-length flat lists of the canonical pairs.
    """
    if len(positions) != len(momenta):
        raise ValueError("positions and momenta must pair up one-to-one")
    f = sp.sympify(f)
    g = sp.sympify(g)
    total = sp.Integer(0)
    for q, p in zip(positions, momenta):
        total += sp.diff(f, q) * sp.diff(g, p) - sp.diff(f, p) * sp.diff(g, q)
    return sp.expand(total)


def weaklyVanishes(expression, constraintExpressions, variables):
    """True if `expression` is zero *on the constraint surface* -- i.e. it lies in
    the ideal generated by the constraint polynomials.

    Polynomial case: reduce modulo a Groebner basis. Non-polynomial fallback:
    strong equality after simplification.
    """
    expression = sp.expand(sp.sympify(expression))
    if expression == 0:
        return True
    if not constraintExpressions:
        return sp.simplify(expression) == 0

    try:
        basis = sp.groebner(
            [sp.expand(c) for c in constraintExpressions], *variables, order="lex"
        )
        remainder = basis.reduce(expression)[1]
        return sp.expand(remainder) == 0
    except (sp.PolynomialError, sp.GeneratorsError, TypeError):
        # give the constraints a chance to substitute, then test strongly
        substituted = expression
        for constraint in constraintExpressions:
            for variable in variables:
                solved = sp.solve(constraint, variable, dict=True)
                if solved:
                    substituted = sp.expand(substituted.subs(solved[0]))
        return sp.simplify(substituted) == 0


def classifyConstraints(constraints, hamiltonian, positions, momenta):
    """First-class / second-class split for a set of `PrimaryConstraint`s.

    phi_a is *first-class* iff {phi_a, phi_b} vanishes weakly for every other
    constraint b (its row of the bracket matrix is weakly zero). Among the
    first-class candidates, if {phi_a, H} does not vanish weakly, consistency
    demands a secondary constraint -- flagged, not computed.

    Returns (classes, bracketMatrix, firstClassCount, secondClassCount,
    secondaryExpected).
    """
    expressions = [c.expression for c in constraints]
    variables = list(positions) + list(momenta)
    n = len(constraints)

    bracket = sp.zeros(n, n)
    for a in range(n):
        for b in range(n):
            bracket[a, b] = poissonBracket(expressions[a], expressions[b], positions, momenta)

    classes = []
    secondaryExpected = False
    firstClassCount = 0
    secondClassCount = 0
    for a in range(n):
        rowWeaklyZero = all(
            weaklyVanishes(bracket[a, b], expressions, variables) for b in range(n)
        )
        if not rowWeaklyZero:
            classes.append("second-class")
            secondClassCount += 1
            continue
        # first-class candidate: check the consistency bracket with H
        consistency = poissonBracket(expressions[a], hamiltonian, positions, momenta)
        if weaklyVanishes(consistency, expressions, variables):
            classes.append("first-class")
        else:
            classes.append("first-class (pending secondary)")
            secondaryExpected = True
        firstClassCount += 1

    return classes, bracket, firstClassCount, secondClassCount, secondaryExpected
